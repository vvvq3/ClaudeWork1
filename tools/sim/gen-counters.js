'use strict';
// Measures who beats whom (equal-gold army duels) and writes js/ai-data.js, the counter table
// the enemy AI uses to choose what to build. Re-run after changing unit stats:
//   node tools/sim/gen-counters.js
const fs = require('fs');
const path = require('path');
const { runTasks } = require('./pool');
const { Sim, ROOT } = require('./engine');

const BUDGETS = [400, 800];
const SEEDS = 8;

(async () => {
  const sim = new Sim();
  const units = sim.eval('UNIT_TYPES.filter(u => !u.isSupport).map(u => ({ id: u.id, cost: u.baseCost }))');
  const ids = units.map(u => u.id);
  const cost = Object.fromEntries(units.map(u => [u.id, u.cost]));
  const tasks = [], meta = [];
  for (const budget of BUDGETS) {
    for (let i = 0; i < ids.length; i++) for (let j = i + 1; j < ids.length; j++) {
      const a = { [ids[i]]: Math.max(1, Math.round(budget / cost[ids[i]])) };
      const b = { [ids[j]]: Math.max(1, Math.round(budget / cost[ids[j]])) };
      for (let s = 1; s <= SEEDS; s++) {
        tasks.push({ fn: 'simDuel', cfg: { a, b, seed: s } }); meta.push([i, j]);
        tasks.push({ fn: 'simDuel', cfg: { a: b, b: a, seed: 100 + s } }); meta.push([j, i]);
      }
    }
  }
  const res = await runTasks(tasks, {});
  const sum = ids.map(() => ids.map(() => 0)), cnt = ids.map(() => ids.map(() => 0));
  res.forEach((r, k) => {
    const [i, j] = meta[k];
    const score = r.a - r.b;
    sum[i][j] += score; cnt[i][j]++; sum[j][i] -= score; cnt[j][i]++;
  });
  const counter = {};
  ids.forEach((a, i) => {
    counter[a] = {};
    ids.forEach((b, j) => { counter[a][b] = i === j ? 0 : Math.round((sum[i][j] / cnt[i][j]) * 100) / 100; });
  });
  const rows = ids.map(a => `  ${a}: { ${ids.map(b => `${b}: ${counter[a][b]}`).join(', ')} }`).join(',\n');
  const out = `// GENERATED by tools/sim/gen-counters.js from army duels at equal gold: do not edit by hand.
// AI_COUNTER[a][b] > 0 means "a beats b" (range -1..1). The enemy AI uses it to pick counters.
const AI_COUNTER = {
${rows}
};
`;
  fs.writeFileSync(path.join(ROOT, 'js', 'ai-data.js'), out);
  console.log(out);
  process.exit(0);
})();
